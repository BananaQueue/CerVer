// Generates src/sealcode/baseline.js from the real artwork. Run once; the
// output is committed so encoder and decoder share one frozen reference and
// never re-sample the PNG at runtime (which could drift).
import { chromium } from 'playwright';
import fs from 'node:fs/promises';

const N = 44;
const png = await fs.readFile('assets/DENR EMB 001.png');
const b = await chromium.launch({ channel: 'chrome', headless: true });
const pg = await b.newPage();
const grid = await pg.evaluate(async ({ src, N }) => {
  const img = new Image(); img.src = src; await img.decode();
  const S = 880, cv = document.createElement('canvas');
  cv.width = S; cv.height = S;
  const cx = cv.getContext('2d', { willReadFrequently: true });
  cx.fillStyle = '#fff'; cx.fillRect(0, 0, S, S); cx.drawImage(img, 0, 0, S, S);
  const d = cx.getImageData(0, 0, S, S).data, cell = S / N, out = [];
  for (let r = 0; r < N; r++) {
    let row = '';
    for (let c = 0; c < N; c++) {
      let ink = 0, n = 0;
      for (let y = Math.floor(r * cell); y < (r + 1) * cell; y++)
        for (let x = Math.floor(c * cell); x < (c + 1) * cell; x++) {
          const o = (y * S + x) * 4;
          if (d[o] * 0.3 + d[o + 1] * 0.59 + d[o + 2] * 0.11 < 200) ink++;
          n++;
        }
      row += ink / n > 0.5 ? '1' : '0';
    }
    out.push(row);
  }
  return out;
}, { src: 'data:image/png;base64,' + png.toString('base64'), N });
await b.close();

const at = (r, c) => (r < 0 || c < 0 || r >= N || c >= N ? 0 : grid[r][c] === '1' ? 1 : 0);
const isRim = (r, c) => !at(r-1,c) || !at(r+1,c) || !at(r,c-1) || !at(r,c+1);
const carriers = [];
for (let r = 0; r < N; r++)
  for (let c = 0; c < N; c++)
    if (at(r, c) && !isRim(r, c)) carriers.push([r, c]);

const out = `// GENERATED by scripts/gen-baseline.mjs from assets/DENR EMB 001.png — do not edit.
//
// The frozen reference for the EMB seal code. Encoder and decoder both read
// this, so the artwork is sampled exactly once, here.
//
//   GRID     the logo as ${N}x${N} tiles, '1' = inked
//   CARRIERS interior inked tiles that may be cleared to carry a bit. A tile is
//            excluded if any 4-neighbour is blank, which keeps every edge in
//            the artwork (disc rim, tree outline, band edges) fixed on every
//            document — that is what the scanner locates and what keeps the
//            mark recognisable.

export const N = ${N};
export const GRID = [
${grid.map((r) => `  '${r}',`).join('\n')}
];
export const CARRIERS = ${JSON.stringify(carriers)};
export const FIXED = (() => {
  const set = new Set(CARRIERS.map(([r, c]) => r * N + c));
  const out = [];
  for (let r = 0; r < N; r++)
    for (let c = 0; c < N; c++) if (!set.has(r * N + c)) out.push([r, c, GRID[r][c] === '1' ? 1 : 0]);
  return out;
})();
`;
await fs.writeFile('src/sealcode/baseline.js', out);
console.log('wrote src/sealcode/baseline.js —', N + 'x' + N, '| carriers', carriers.length,
  '| inked', grid.join('').split('1').length - 1);
